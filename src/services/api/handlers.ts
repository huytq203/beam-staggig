export const getResponseMessage = (key: string) => {
  const values = Object.values(GlobalResponseMessageCodes);
  const index = Object.keys(GlobalResponseMessageCodes).indexOf(key);
  if (index == -1) {
    return key;
  }
  return values[index];
};
